#!/usr/bin/env python3
"""std_doc.py —— std 参考页生成器 v2(ctron-doc JSON 后端;计划 2026-10-09-api-docs-plan.md W1)

真源 = lib/std/*.ct 源码注释(模块头注 + 每个 pub decl 前注释);解析面 =
compiler/ctc.sh doc <file> --format=json(driver_doc.ct iface 投影,T50 S0),
Python 只做渲染。v1 的源码正则路径退役(漏 impl/trait 面、不读注释,且模块
glob 还停在库根布局前的根级 std/,0930 后 glob 落空)。

页形:# std.<mod> / 元行(tier·since,自头注剥出)/ 手写区(<!-- hand:desc -->
界定,再生保留;新页 = 模块头注全文)/ 生成区(pub struct → pub enum →
trait → impl → pub fn;说明列 = 源码注释,缺注 = —)。

用法:
  python3 tools/std_doc.py           # 缺页生成 + 全部生成区刷新(手写区保留)
  python3 tools/std_doc.py --check   # 门禁:重生成与盘上逐字节一致,漂移 rc=1
  python3 tools/std_doc.py --force   # 手写区一并重置为模块头注
"""
import argparse
import json
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STD = ROOT / "lib" / "std"
OUT = ROOT / "website" / "docs" / "std"
CTC = ROOT / "compiler" / "ctc.sh"
DOMAINS = ["net", "http", "tls", "db", "ffi"]  # 域包参考页(lib/<域>/**/*.ct;rt 无 .ct 门面,仅指针页)

HAND_OPEN = "<!-- hand:desc -->"
HAND_CLOSE = "<!-- /hand:desc -->"
TODO_V1 = "TODO: one-line module description."


def ctron_doc_json(path: pathlib.Path) -> dict:
    """ctc.sh doc --format=json;stdout=JSON、stderr=宿主杂音,必须分离流。
    驱动重拼撞机刷中间态会瞬时假红(E1001),重试一次。
    CTRON_SITEPATH 注入库根:ctc.sh doc 未像 emit 注入 STDPATH(S4-⑤ 缺口登记),
    域包子目录(frm/* 等)的 use <域>.<mod> 解析需显式指路。"""
    env = dict(os.environ, CTRON_SITEPATH=str(ROOT / "lib"))
    last = ""
    for _ in range(2):
        r = subprocess.run([str(CTC), "doc", str(path), "--format=json"],
                           cwd=ROOT, capture_output=True, text=True, env=env)
        if r.returncode == 0:
            try:
                return json.loads(r.stdout)
            except json.JSONDecodeError as e:
                last = f"JSON 解析失败: {e}"
        else:
            last = (r.stdout + r.stderr).strip().splitlines()[-1] if (r.stdout + r.stderr).strip() else f"rc={r.returncode}"
    sys.exit(f"std_doc: ctron-doc 对 {path.name} 两趟皆败: {last}")


def esc(s: str) -> str:
    # 尖括号转义:doc 注释里的 `<…>` 会被 mkdocs 当疑似 HTML 标签(strict 下 INFO、
    # 渲染面吞字);表格单元内不在代码跨度里的说明文本一律字面转义。
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace("|", "\\|").replace("\n", "<br>"))


def split_meta(doc: str):
    """从头注剥 tier/since 行入元行,余下为手写区缺省文本。"""
    tier = since = ""
    body = []
    for ln in doc.splitlines():
        m = re.match(r"^\s*@?\s*tier:\s*(\S+)\s*$", ln)
        if m:
            tier = m.group(1)
            continue
        m = re.match(r"^\s*since:\s*(.+?)\s*$", ln)
        if m:
            since = m.group(1)
            continue
        body.append(ln)
    text = "\n".join(body).strip()
    text = re.sub(r"^[a-z][\w/]*\.ct\s*——\s*", "", text)
    # 中和假链接:Ctron 泛型/下标形 `[T](x` 会被 mkdocs 当 markdown 链接目标
    # (strict 红);源头派生文本统一转义 `](`,手写区不受影响
    text = text.replace("](", "]&#40;")
    return tier, since, text


def fn_sig(it: dict) -> str:
    ps = []
    for p in it.get("params", []):
        if p.get("vaargs"):
            ps.append("...")
        else:
            ps.append(("var " if p.get("mutable") else "") + p["name"] + ": " + p["type"])
    g = "[" + ", ".join(it["generics"]) + "]" if it.get("generics") else ""
    return f"{it['name']}{g}({', '.join(ps)})"


def hand_desc_of(page: pathlib.Path, src_text: str) -> str:
    """手写区缺省:已有页取界定区;v1 旧页迁首段(TODO 占位则弃);新页 = 模块头注。"""
    if page.exists():
        t = page.read_text()
        if HAND_OPEN in t and HAND_CLOSE in t:
            return t.split(HAND_OPEN, 1)[1].split(HAND_CLOSE, 1)[0].strip("\n")
        m = re.search(r"# std\.\w+\s*\n\n(.*?)\n\n## ", t, re.S)
        if m and m.group(1).strip() != TODO_V1:
            return m.group(1).strip()
    return src_text


def render(title: str, data: dict, hand: str, drop_externs: bool = False) -> str:
    tier, since, src_text = split_meta(data.get("doc", ""))
    meta = " · ".join(f"`{k}: {v}`" for k, v in (("tier", tier), ("since", since)) if v)
    out = [
        f"<!-- generated by tools/std_doc.py v2; regenerate refreshes all but the hand region -->\n",
        f"# {title}\n",
    ]
    if meta:
        out.append(f"\n{meta}\n")
    if not hand:
        hand = "(待补:模块简介——回源头头注或在此手写)"
    out.append(f"\n{HAND_OPEN}\n{hand}\n{HAND_CLOSE}\n")

    iface = data.get("iface", [])
    if drop_externs:
        # 域包 use 合并将 bind*.ct 的 extern 窄桥并入 iface(用户不接触面),渲染剔除
        iface = [i for i in iface if i["kind"] != "extern"]
    structs = [i for i in iface if i["kind"] == "struct"]
    enums = [i for i in iface if i["kind"] == "enum"]
    traits = [i for i in iface if i["kind"] == "trait"]
    impls = [i for i in iface if i["kind"] == "impl"]
    fns = [i for i in iface if i["kind"] == "fn"]

    if structs:
        out.append("\n## pub struct\n")
        for s in structs:
            g = "[" + ", ".join(s["generics"]) + "]" if s.get("generics") else ""
            out.append(f"\n**struct {s['name']}{g}**\n")
            if s.get("doc"):
                out.append(f"\n{esc(s['doc'])}\n")
            out.append("\n| Field | Type |\n|---|---|\n")
            for f in s.get("fields", []):
                name = ("var " if f.get("mutable") else "") + f["name"]
                out.append(f"| `{name}` | `{f['type']}` |\n")
    if enums:
        out.append("\n## pub enum\n")
        for e in enums:
            g = "[" + ", ".join(e["generics"]) + "]" if e.get("generics") else ""
            out.append(f"\n**enum {e['name']}{g}**\n")
            if e.get("doc"):
                out.append(f"\n{esc(e['doc'])}\n")
            out.append("\n| Variant | Payload |\n|---|---|\n")
            for v in e.get("variants", []):
                if v.get("tuple") is not None:
                    pay = "(" + ", ".join(v["tuple"]) + ")"
                elif v.get("fields") is not None:
                    pay = "{ " + ", ".join(("var " if f.get("mutable") else "") + f["name"] + ": " + f["type"] for f in v["fields"]) + " }"
                else:
                    pay = ""
                out.append(f"| `{v['name']}` | `{pay}` |\n" if pay else f"| `{v['name']}` | — |\n")
    if traits:
        out.append("\n## trait\n")
        for t in traits:
            out.append(f"\n**trait {t['name']}**\n")
            if t.get("doc"):
                out.append(f"\n{esc(t['doc'])}\n")
            out.append("\n```ct\n" + "\n".join(t.get("sigs", [])) + "\n```\n")
    if impls:
        out.append("\n## impl\n")
        for i in impls:
            sig = i.get("sig", "")
            out.append(f"\n```ct\n{sig}" + ("\n" + "\n".join("    " + s for s in i.get("sigs", [])) if i.get("sigs") else "") + "\n```\n")
    if fns:
        out.append("\n## pub fn\n")
        out.append("\n| Signature | Returns | Description |\n|---|---|---|\n")
        for f in fns:
            ret = f.get("ret", "")
            desc = esc(f["doc"]) if f.get("doc") else "—"
            out.append(f"| `{fn_sig(f)}` | `{ret}` | {desc} |\n")
    out.append("\n")
    return "".join(out)


def domain_pages(domain: str):
    """域包页清单:[(源文件, 页名)]。rglob 全子目录(frm/ 中间件族),跳过
    c_src/ 与 bind*.ct(extern 窄桥,用户不接触);页名 = 相对路径点连(frm/auth → frm.auth)。"""
    base = ROOT / "lib" / domain
    out = []
    for p in sorted(base.rglob("*.ct")):
        rel = p.relative_to(base)
        if "c_src" in rel.parts:
            continue
        if p.stem.startswith("bind"):
            continue
        out.append((p, ".".join(rel.with_suffix("").parts)))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate std/domain reference pages via ctron-doc JSON backend.")
    ap.add_argument("--check", action="store_true", help="drift gate: rendered pages must equal on-disk bytes (std + domains)")
    ap.add_argument("--force", action="store_true", help="also reset hand regions to module doc comments")
    ap.add_argument("--domain", action="append", default=[], help="generate one domain's pages (default with --check: all)")
    ns = ap.parse_args()

    domains = DOMAINS if ns.check else ns.domain
    drift = []

    # ---- std 26 页 + 索引 ----
    mods = sorted(p.stem for p in STD.glob("*.ct"))
    if not mods:
        sys.exit(f"std_doc: {STD} 无模块,glob 落空")

    index = [
        "# Std Reference\n\n",
        "Signature tables and per-item descriptions are generated by "
        "[tools/std_doc.py](https://github.com/ZturnLibs/Ctron/blob/main/tools/std_doc.py) "
        "from `lib/std/*.ct` source doc comments (ctron-doc iface projection). "
        "Module description sections between the `hand:desc` markers are hand-written.\n\n",
        "> Agent channel: `compiler/ctc.sh doc lib/std/<mod>.ct --format=json` "
        "(pub symbol table with doc comments, deterministic).\n\n",
        "> Chinese translations of the Std Reference are pending; descriptions follow "
        "source comments (mostly Chinese) for now.\n\n",
        "| Module | Page |\n|---|---|\n",
    ]

    drift = []
    for mod in mods:
        data = ctron_doc_json(STD / f"{mod}.ct")
        page = OUT / f"{mod}.md"
        src_text = split_meta(data.get("doc", ""))[2]
        hand = src_text if ns.force else hand_desc_of(page, src_text)
        rendered = render(f"std.{mod}", data, hand)
        if ns.check:
            if not page.exists() or page.read_text() != rendered:
                drift.append(f"std/{mod}")
        else:
            page.write_text(rendered)
        index.append(f"| std.{mod} | [{mod}.md]({mod}.md) |\n")

    idx = OUT / "README.md"
    if ns.check:
        if not idx.exists() or idx.read_text() != "".join(index):
            drift.append("std/README.md(index)")

    # ---- 域包页(--domain 显式生成;--check 全域对拍)----
    dstats = []
    for d in domains:
        pages = domain_pages(d)
        dout = ROOT / "website" / "docs" / d
        for src, page_name in pages:
            data = ctron_doc_json(src)
            page = dout / (page_name.replace(".", "_") + ".md")
            src_text = split_meta(data.get("doc", ""))[2]
            hand = src_text if ns.force else hand_desc_of(page, src_text)
            rendered = render(f"{d}.{page_name}", data, hand, drop_externs=True)
            if ns.check:
                if not page.exists() or page.read_text() != rendered:
                    drift.append(f"{d}/{page.name}")
            else:
                page.parent.mkdir(parents=True, exist_ok=True)
                page.write_text(rendered)
                dstats.append(f"{d}/{page.name}")

    if ns.check:
        if drift:
            print("std_doc --check: 漂移 " + " ".join(drift) + " —— 复跑 python3 tools/std_doc.py [--domain <域>] 后随批提交")
            return 1
        print(f"std_doc --check: std {len(mods)} 页 + index" + (" + 域包 " + str(sum(len(domain_pages(d)) for d in DOMAINS)) + " 页" if domains == DOMAINS else "") + " 逐字节一致")
        return 0

    idx.write_text("".join(index))
    dom = ("" if not dstats else f";域包页 {len(dstats)} 张[{', '.join(dstats[:6])}{'…' if len(dstats) > 6 else ''}]")
    print(f"std_doc: std {len(mods)} 模块页 + index -> {OUT}{dom}(生成区已刷新;手写区保留{';--force 已重置' if ns.force else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
